/**
 * 生成协议详情页的 Page 配置（所有协议共用同一个通用详情页）
 * 内容优先取后台「协议管理」（接口下发 Markdown）：
 *   - 正文拆成「文本块 + 图片块」：文本交 rich-text，图片交原生 image（各端稳定显示、可点击放大）；
 *   - 后台已停用 / 未配置（not_published）：展示「当前协议未发布」兜底；
 *   - 其它情况（网络异常、协议表未初始化等）拉取失败时回退内置内容。
 * @param {string} key 协议标识；留空时从页面参数 ?key= 读取（通用详情页）
 * @param {string} defaultTitle 加载中的兜底标题
 */
function agreementPageConfig(key, defaultTitle) {
  return {
    data: {
      title: defaultTitle || '协议内容',
      updatedAt: '',
      blocks: [],           // 正文块：{type:'html',html} 或 {type:'image',src,alt}
      notPublished: false   // 后台已停用/未配置时展示「当前协议未发布」兜底
    },
    onLoad: function (options) {
      var k = key || (options && options.key) || '';
      this.__akey = k;
      this.setData({ notPublished: false });
      var doc = docGet(k);
      if (doc) {
        this.setData({
          title: doc.title,
          updatedAt: doc.updatedAt,
          blocks: this.toBlocks(doc.content)
        });
      }
      this.loadAgreementFromServer();
    },
    // Markdown → 块序列（图片相对路径自动补全为完整地址）
    toBlocks: function (md) {
      var markdownToHtml = require('./markdown.js');
      var api = require('./api.js');
      return markdownToHtml.markdownToBlocks(md || '', { resolveUrl: api.getFileUrl });
    },
    // 正文图片点击放大
    previewImage: function (e) {
      var src = e.currentTarget.dataset.src;
      if (src) wx.previewImage({ current: src, urls: [src] });
    },
    // 关于我们
    goAbout: function () {
      wx.navigateTo({ url: '/pages/about/index' });
    },
    // 联系客服：先询问「在线客服 / 其他联系方式」
    openContactGuide: function () {
      var guide = this.selectComponent('#contactGuide');
      if (guide) guide.open();
    },
    loadAgreementFromServer: function () {
      var that = this;
      var k = this.__akey;
      if (!k) return;
      var api = require('./api.js');
      api.getAgreement(k).then(function (res) {
        var d = (res && res.data) || {};
        if (!d.content) return;
        that.setData({
          title: d.title || that.data.title,
          updatedAt: d.updated_at ? String(d.updated_at).slice(0, 10) : '',
          blocks: that.toBlocks(d.content),
          notPublished: false
        });
      }).catch(function (err) {
        // 后台明确「未发布」（未配置/已停用）：清空内置内容，改展示兜底提示
        if (err && err.data && err.data.not_published) {
          that.setData({ notPublished: true, blocks: [], updatedAt: '' });
        }
        // 其它错误（网络异常、协议表未初始化等）：保留内置内容，保证离线仍可阅读
      });
    }
  };
}

