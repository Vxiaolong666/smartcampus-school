/**
 * 协议详情统一路径
 * ------------------------------------------------------------------
 * 所有协议（内置协议与后台新建的）都走同一个通用详情页：detail/index?key=xxx，
 * 页面内按 key 取内容（以后台「协议管理」为准，失败回退内置内容）。
 * 好处：新增协议无需再改页面/路由，一处维护。
 */
function resolvePath(key) {
  if (!key) return '';
  return '/pages/agreement/detail/index?key=' + encodeURIComponent(key);
}

